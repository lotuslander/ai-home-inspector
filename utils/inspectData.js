// 结构化指标判定：输入数值/选择 → 返回 {status:'ok'|'mid'|'bad', tip}
// type: max=越大越差 / min=越小越差 / range=应落在区间内 / choice=定性选择
function judgeMetric(metric, value) {
  if (metric.type === 'choice') {
    const hit = (metric.options || []).find(o => o.label === value);
    if (!hit) return null;
    return { status: hit.status, tip: hit.tip };
  }
  const v = parseFloat(value);
  if (isNaN(v)) return null;
  if (metric.type === 'max') {
    if (v <= metric.limit1) return { status: 'ok', tip: metric.ok };
    if (v <= metric.limit2) return { status: 'mid', tip: metric.mid };
    return { status: 'bad', tip: metric.bad };
  }
  if (metric.type === 'min') {
    if (v >= metric.limit1) return { status: 'ok', tip: metric.ok };
    if (v >= metric.limit2) return { status: 'mid', tip: metric.mid };
    return { status: 'bad', tip: metric.bad };
  }
  if (metric.type === 'range') {
    const lo = metric.range[0], hi = metric.range[1], tol = metric.tol || (hi - lo) * 0.25;
    if (v >= lo && v <= hi) return { status: 'ok', tip: metric.ok };
    if (v >= lo - tol && v <= hi + tol) return { status: 'mid', tip: metric.mid };
    return { status: 'bad', tip: metric.bad };
  }
  return null;
}

