// 精准匹配：按检查项名称/关键词返回规范依据（确定性，返回第一条命中）
function matchNorm(name, category, note){
  const text = (name||'') + ' ' + (category||'') + ' ' + (note||'');
  for(const r of RULE_MAP){
    for(const kw of r.kw){
      if(text.indexOf(kw) >= 0) return { code: r.code, point: r.point };
    }
  }
  return null;
}

// 报告文本用：完整拼装规范依据行
function normLine(name, category, note){
  const m = matchNorm(name, category, note);
  if(!m) return '';
  return m.code + '：' + m.point;
}

// 规范页分类导航：按cat字段确定性聚合
const CATEGORY_ORDER = ['墙面','地面','防水','门窗','电气','给排水','安全','层高面积','烟道通风','采暖'];
const CATEGORY_GUIDE = CATEGORY_ORDER.map(cat => ({
  cat: cat,
  rules: RULE_MAP.filter(r => r.cat === cat)
}));

module.exports = { matchNorm, normLine, CATEGORY_GUIDE, RULE_MAP };
